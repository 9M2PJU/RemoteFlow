#!/usr/bin/env python3
"""Generates the light-theme block at the end of src/index.css from Tailwind's palette.

Usage (from the project root, after `npm install`):
    python3 scripts/gen-theme-css.py          # rewrites the generated block in src/index.css

Components are written with the dark palette only; `html.light` re-maps the Tailwind colour
variables, and `.rf-dark` restores the original (dark) palette inside the light theme.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARKER = "/* ---- Light theme: re-mapped palette"

theme = (ROOT / "node_modules/tailwindcss/theme.css").read_text(encoding="utf-8")
pal = {(m[1], int(m[2])): m[3].strip() for m in re.finditer(r"--color-([a-z]+)-(\d+):\s*([^;]+);", theme)}

SLATE = {950: 50, 900: 100, 800: 200, 700: 300, 600: 400, 500: 500, 400: 600, 300: 700, 200: 800, 100: 900, 50: 950}
ACCENT = {50: 900, 100: 800, 200: 800, 300: 700, 400: 600, 800: 200, 900: 100, 950: 50}
ACCENTS = ["red", "orange", "amber", "yellow", "lime", "green", "emerald", "teal", "cyan", "sky",
           "blue", "indigo", "violet", "purple", "fuchsia", "pink", "rose"]

out = [MARKER + " (generated by scripts/gen-theme-css.py, see src/theme/index.ts) ---- */", "html.light {", "  color-scheme: light;"]
out += [f"  --color-slate-{k}: {pal[('slate', v)]};" for k, v in sorted(SLATE.items(), reverse=True)]
out += [f"  --color-{a}-{k}: {pal[(a, v)]};" for a in ACCENTS for k, v in sorted(ACCENT.items())]
out += [f"  --color-white: {pal[('slate', 900)]};", "}"]

sels = [f'[class~="{p}-{a}-{k}"]' for a in ACCENTS for k in (500, 600, 700) for p in ("bg", "from")]
out.append("/* White text on solid coloured buttons and badges stays white */")
out.append(",\n".join(f"html.light {s}.text-white, html.light {s} .text-white" for s in sels) + " {\n  color: #fff;\n}")

out += ["/* Dark island inside the light theme (e.g. toolbar over a terminal kept dark): original palette */",
        "html.light .rf-dark {", "  color-scheme: dark;"]
out += [f"  --color-slate-{k}: {pal[('slate', k)]};" for k in sorted(SLATE, reverse=True)]
out += [f"  --color-{a}-{k}: {pal[(a, k)]};" for a in ACCENTS for k in sorted(ACCENT)]
out += ["  --color-white: #fff;", "}"]

css_path = ROOT / "src/index.css"
css = css_path.read_text(encoding="utf-8")
idx = css.find(MARKER)
if idx < 0:
    raise SystemExit("marker not found in src/index.css")
css_path.write_text(css[:idx] + "\n".join(out) + "\n", encoding="utf-8")
print("src/index.css updated")
