#!/usr/bin/env bash
# Builds a native Arch Linux pacman package: remoteflow-<version>-1-x86_64.pkg.tar.zst
# Can run on any Linux distro (Ubuntu/Debian/Arch/Docker) using tar + zstd + fakeroot (or tar --owner=0 --group=0),
# so CI (Ubuntu) and Docker builds can produce a genuine .pkg.tar.zst alongside .deb, .rpm, and .AppImage!
#
# Usage:
#   bash scripts/build-arch-pkg.sh [BINARY_PATH] [OUTPUT_DIR]
set -euo pipefail

SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
REPO_ROOT="$(CDPATH= cd -- "$SCRIPT_DIR/.." && pwd)"

BINARY_PATH="${1:-$REPO_ROOT/src-tauri/target/release/remoteflow}"
OUT_DIR="${2:-$(pwd)}"
PKGVER="${REMOTEFLOW_VERSION:-$(node -p "require('$REPO_ROOT/package.json').version" 2>/dev/null || grep -m1 '"version"' "$REPO_ROOT/package.json" | sed -E 's/.*"version": *"([^"]+)".*/\1/')}"
PKGREL="${PKGREL:-1}"
PKGNAME="remoteflow"
ARCH="x86_64"
PKG_FILENAME="${PKGNAME}-${PKGVER}-${PKGREL}-${ARCH}.pkg.tar.zst"

if [[ ! -f "$BINARY_PATH" ]]; then
  printf 'Error: Compiled binary not found at %s\n' "$BINARY_PATH" >&2
  exit 1
fi

if ! command -v zstd >/dev/null 2>&1; then
  printf 'Error: zstd is required to build %s\n' "$PKG_FILENAME" >&2
  exit 1
fi

STAGE_DIR="$(mktemp -d)"
trap 'rm -rf "$STAGE_DIR"' EXIT

# Populate package filesystem tree
install -Dm755 "$BINARY_PATH" "$STAGE_DIR/usr/bin/remoteflow"
install -Dm644 "$REPO_ROOT/src-tauri/icons/32x32.png" "$STAGE_DIR/usr/share/icons/hicolor/32x32/apps/remoteflow.png"
install -Dm644 "$REPO_ROOT/src-tauri/icons/128x128.png" "$STAGE_DIR/usr/share/icons/hicolor/128x128/apps/remoteflow.png"
install -Dm644 "$REPO_ROOT/src-tauri/icons/128x128@2x.png" "$STAGE_DIR/usr/share/icons/hicolor/256x256@2x/apps/remoteflow.png"
install -Dm644 "$REPO_ROOT/src-tauri/icons/icon.png" "$STAGE_DIR/usr/share/icons/hicolor/512x512/apps/remoteflow.png"
install -Dm644 "$REPO_ROOT/src-tauri/icons/icon.svg" "$STAGE_DIR/usr/share/icons/hicolor/scalable/apps/remoteflow.svg"
install -Dm644 "$REPO_ROOT/LICENSE" "$STAGE_DIR/usr/share/licenses/remoteflow/LICENSE"
install -Dm644 "$REPO_ROOT/README.md" "$STAGE_DIR/usr/share/doc/remoteflow/README.md"
install -Dm644 "$REPO_ROOT/docs/LINUX.md" "$STAGE_DIR/usr/share/doc/remoteflow/LINUX.md"

install -dm755 "$STAGE_DIR/usr/share/applications"
cat > "$STAGE_DIR/usr/share/applications/remoteflow.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=RemoteFlow
Comment=SSH, SFTP and RDP connection manager
Exec=/usr/bin/remoteflow
Icon=remoteflow
Terminal=false
Categories=Development;Network;
StartupWMClass=remoteflow
EOF
chmod 644 "$STAGE_DIR/usr/share/applications/remoteflow.desktop"

# Calculate installed size in bytes
INSTALLED_SIZE="$(du -sb "$STAGE_DIR/usr" | awk '{print $1}')"
BUILD_DATE="${SOURCE_DATE_EPOCH:-$(date +%s)}"

# Write pacman .PKGINFO metadata
cat > "$STAGE_DIR/.PKGINFO" <<EOF
# Generated by build-arch-pkg.sh for RemoteFlow
pkgname = ${PKGNAME}
pkgbase = ${PKGNAME}
pkgver = ${PKGVER}-${PKGREL}
pkgdesc = Cross-platform SSH, SFTP and RDP connection manager with an encrypted vault (Tauri 2 + Rust + React)
url = https://github.com/9M2PJU/RemoteFlow
builddate = ${BUILD_DATE}
packager = 9M2PJU <9m2pju@hamradio.my>
size = ${INSTALLED_SIZE}
arch = ${ARCH}
license = MIT
conflict = remoteflow-bin
conflict = remoteflow-git
provides = remoteflow
depend = webkit2gtk-4.1
depend = gtk3
depend = openssl
depend = libx11
depend = dbus
depend = zlib
depend = gcc-libs
depend = glibc
depend = hicolor-icon-theme
depend = xdg-utils
optdepend = freerdp: Native embedded or external FreeRDP client
optdepend = xorg-xwayland: Embedded native FreeRDP session under Wayland
optdepend = which: Required for FreeRDP binary detection
optdepend = zenity: Native GTK file and folder picker dialog
optdepend = kdialog: Native KDE file and folder picker dialog
optdepend = wl-clipboard: Reliable system clipboard copying under Wayland
optdepend = xclip: Reliable system clipboard copying under X11
optdepend = openssh: SSH agent authentication
EOF

# Generate .MTREE (pacman package file manifest)
(
  cd "$STAGE_DIR"
  if command -v bsdtar >/dev/null 2>&1; then
    LANG=C bsdtar -czf .MTREE --format=mtree \
      --options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' \
      .PKGINFO usr
  else
    # Fallback minimal gzipped mtree header if libarchive-tools/bsdtar isn't installed
    {
      printf '#mtree\n'
      printf '/set type=file uid=0 gid=0 mode=644\n'
    } | gzip -n -c > .MTREE
  fi
)

mkdir -p "$OUT_DIR"
OUT_PATH="$(CDPATH= cd -- "$OUT_DIR" && pwd)/$PKG_FILENAME"

(
  cd "$STAGE_DIR"
  if [[ -f .MTREE ]] && command -v bsdtar >/dev/null 2>&1; then
    LANG=C tar --owner=0 --group=0 --numeric-owner -cf - .PKGINFO .MTREE usr | zstd -q -19 -T0 -f -o "$OUT_PATH"
  else
    LANG=C tar --owner=0 --group=0 --numeric-owner -cf - .PKGINFO usr | zstd -q -19 -T0 -f -o "$OUT_PATH"
  fi
)

printf '✓ Built Arch Linux package: %s\n' "$OUT_PATH"
